"""Generate the CLI reference from the real argparse parser.

The CLI has ~190 options spread over `sms_tool/cli.py` and `sms_tool/cli_parsers/`.
`--help` is the only reference today, which makes review and docs search hard and
lets a flag ship undocumented.

    python scripts/generate_cli_reference.py            # print markdown
    python scripts/generate_cli_reference.py --write    # write docs/current/cli-reference.md
    python scripts/generate_cli_reference.py --check    # exit 1 when stale

`--check` is what `tests/governance/test_cli_reference.py` runs: a stale
reference fails the suite instead of silently describing last month's flags.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "docs" / "current" / "cli-reference.md"

HEADER = """# CLI Reference

<!-- Generated by scripts/generate_cli_reference.py --write. Do not edit by hand. -->

`python chatgpt_phone_reg.py` (or `python -m sms_tool`) builds this parser. The
table is generated from it, so a flag that exists is listed and a flag that was
removed disappears. Options hidden from `--help` (internal IPC and test seams)
are omitted.

| Option | Value | Help |
| --- | --- | --- |
"""


def _cell(text: str) -> str:
    return " ".join(str(text or "").split()).replace("|", "\\|")


def _value(action: argparse.Action) -> str:
    if action.choices:
        return "choices: " + ", ".join(f"`{choice}`" for choice in action.choices)
    metavar = str(action.metavar or "").strip()
    if metavar:
        return f"`{metavar}`"
    if action.nargs == 0:
        return "—"
    return "value"


def _row(action: argparse.Action) -> str | None:
    help_text = action.help
    if help_text is None or str(help_text).strip() in {"", "==SUPPRESS=="}:
        return None
    option = ", ".join(f"`{name}`" for name in action.option_strings)
    required = " **(required)**" if action.required else ""
    return f"| {option} | {_value(action)} | {_cell(help_text)}{required} |"


def render() -> str:
    # Running a script from scripts/ puts scripts/ on sys.path, not the repo
    # root; the package is imported from the checkout being documented.
    if str(ROOT) not in sys.path:
        sys.path.insert(0, str(ROOT))
    from sms_tool.cli import build_parser

    parser = build_parser()
    rows = [row for action in parser._actions if action.option_strings for row in [_row(action)] if row]
    rows.sort(key=lambda row: row.split("`")[1])
    return HEADER + "\n".join(rows) + "\n"


def main(argv: list[str]) -> int:
    markdown = render()
    if "--write" in argv:
        TARGET.write_text(markdown, encoding="utf-8", newline="\n")
        print(f"wrote {TARGET.relative_to(ROOT)}")
        return 0
    if "--check" in argv:
        current = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else ""
        if current != markdown:
            print(
                f"{TARGET.relative_to(ROOT)} is stale; run "
                "`python scripts/generate_cli_reference.py --write`.",
                file=sys.stderr,
            )
            return 1
        print("CLI reference is current")
        return 0
    sys.stdout.write(markdown)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
