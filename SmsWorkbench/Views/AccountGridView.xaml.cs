// Opted into nullable reference checking file-by-file - see the note in
// PaymentBatchService.cs for why the project-wide switch stays `annotations`.
#nullable enable

namespace SmsWorkbench
{
    /// <summary>
    /// Account table and its context menu.
    ///
    /// Owns the two behaviours that used to be window code-behind: sorting
    /// (delegated to <see cref="PoolViewModel.SortBy"/>) and row selection
    /// (selecting a row ticks its checkbox). The window only reads
    /// <see cref="SelectedRow"/> and calls <see cref="ClearSelection"/>.
    /// </summary>
    public partial class AccountGridView : UserControl
    {
        public static readonly DependencyProperty PoolProperty = DependencyProperty.Register(
            nameof(Pool),
            typeof(PoolViewModel),
            typeof(AccountGridView),
            new PropertyMetadata(null));

        // Resolved by name: per-file analyzers do not see AccountGridView.g.cs.
        private readonly System.Windows.Controls.DataGrid accountGrid;

        public AccountGridView()
        {
            // Generated by the WPF markup compiler into AccountGridView.g.cs.
            InitializeComponent();
            accountGrid = (System.Windows.Controls.DataGrid)(
                FindName("AccountGrid")
                ?? throw new InvalidOperationException("AccountGridView.xaml is missing x:Name=\"AccountGrid\""));
        }

        public PoolViewModel? Pool
        {
            get => (PoolViewModel?)GetValue(PoolProperty);
            set => SetValue(PoolProperty, value);
        }

        /// <summary>The row currently selected in the grid, or null.</summary>
        public PoolRow? SelectedRow => accountGrid.SelectedItem as PoolRow;

        /// <summary>Clears the grid widget when the view model's selection is cleared.</summary>
        public void ClearSelection()
        {
            accountGrid.SelectedItem = null;
            accountGrid.SelectedIndex = -1;
            accountGrid.UnselectAll();
        }

        // Sorting is handled here, not on the window: the column indicators and
        // the view model's order must change together.
        private void AccountGrid_Sorting(object sender, DataGridSortingEventArgs e)
        {
            string member = (e.Column.SortMemberPath ?? "").Trim();
            if (member.Length == 0 || Pool is null)
            {
                return;
            }

            e.Handled = true;
            ListSortDirection next = e.Column.SortDirection == ListSortDirection.Ascending
                ? ListSortDirection.Descending
                : ListSortDirection.Ascending;
            foreach (DataGridColumn column in accountGrid.Columns)
            {
                column.SortDirection = null;
            }

            e.Column.SortDirection = next;
            Pool.SortBy(member, next);
        }

        private void AccountGrid_SelectionChanged(object sender, SelectionChangedEventArgs e)
        {
            foreach (object item in e.AddedItems)
            {
                if (item is PoolRow row)
                {
                    row.IsChecked = true;
                }
            }
        }
    }
}
