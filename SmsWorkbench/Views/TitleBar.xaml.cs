using System.Windows.Input;

namespace SmsWorkbench.Views
{
    /// <summary>
    /// Custom title bar (drag surface + minimize / maximize-restore / close).
    ///
    /// The handlers resolve the host through <see cref="Window.GetWindow(DependencyObject)"/>
    /// and mirror its maximized state into <see cref="IsWindowMaximized"/> so the
    /// caption button flips cleanly between maximize and restore glyphs/tooltips.
    /// </summary>
    public partial class TitleBar : UserControl
    {
        public static readonly DependencyProperty IsWindowMaximizedProperty = DependencyProperty.Register(
            nameof(IsWindowMaximized),
            typeof(bool),
            typeof(TitleBar),
            new PropertyMetadata(false));

        private Window? hostWindow;

        public bool IsWindowMaximized
        {
            get => (bool)GetValue(IsWindowMaximizedProperty);
            private set => SetValue(IsWindowMaximizedProperty, value);
        }

        public TitleBar()
        {
            // Generated by the WPF markup compiler into TitleBar.g.cs.
            InitializeComponent();
            Loaded += OnLoaded;
            Unloaded += OnUnloaded;
        }

        private void OnLoaded(object sender, RoutedEventArgs e)
        {
            DetachHostWindow();
            hostWindow = Window.GetWindow(this);
            if (hostWindow is not null)
            {
                hostWindow.StateChanged += HostWindow_StateChanged;
                SyncMaximizedState();
            }
        }

        private void OnUnloaded(object sender, RoutedEventArgs e)
        {
            DetachHostWindow();
        }

        private void DetachHostWindow()
        {
            if (hostWindow is not null)
            {
                hostWindow.StateChanged -= HostWindow_StateChanged;
                hostWindow = null;
            }
        }

        private void HostWindow_StateChanged(object? sender, EventArgs e)
        {
            SyncMaximizedState();
        }

        private void SyncMaximizedState()
        {
            IsWindowMaximized = hostWindow?.WindowState == WindowState.Maximized;
        }

        private void TitleBar_MouseLeftButtonDown(object sender, MouseButtonEventArgs e)
        {
            Window? window = Window.GetWindow(this);
            if (window is null)
            {
                return;
            }

            if (e.ClickCount == 2)
            {
                window.WindowState = window.WindowState == WindowState.Maximized
                    ? WindowState.Normal
                    : WindowState.Maximized;
                return;
            }

            window.DragMove();
        }

        private void MinimizeButton_Click(object sender, RoutedEventArgs e)
        {
            Window? window = Window.GetWindow(this);
            if (window is not null)
            {
                window.WindowState = WindowState.Minimized;
            }
        }

        private void MaximizeButton_Click(object sender, RoutedEventArgs e)
        {
            Window? window = Window.GetWindow(this);
            if (window is null)
            {
                return;
            }

            window.WindowState = window.WindowState == WindowState.Maximized
                ? WindowState.Normal
                : WindowState.Maximized;
        }

        private void CloseButton_Click(object sender, RoutedEventArgs e)
        {
            Window.GetWindow(this)?.Close();
        }
    }
}
