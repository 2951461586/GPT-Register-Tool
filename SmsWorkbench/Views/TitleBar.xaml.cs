#nullable enable

using System.Windows.Input;

namespace SmsWorkbench
{
    /// <summary>
    /// Custom title bar (drag surface + minimize / maximize / close).
    ///
    /// The handlers used to live on <c>MainWindow</c> and reach the window
    /// implicitly; a UserControl has no such implicit host, so every one of them
    /// resolves it through <see cref="Window.GetWindow(DependencyObject)"/>.
    /// No window state is duplicated here.
    /// </summary>
    public partial class TitleBar : UserControl
    {
        public TitleBar()
        {
            // Generated by the WPF markup compiler into TitleBar.g.cs.
            InitializeComponent();
        }

        private void TitleBar_MouseLeftButtonDown(object sender, MouseButtonEventArgs e)
        {
            Window? window = Window.GetWindow(this);
            if (window is null)
            {
                return;
            }

            if (e.ClickCount == 2)
            {
                window.WindowState = window.WindowState == WindowState.Maximized
                    ? WindowState.Normal
                    : WindowState.Maximized;
                return;
            }

            window.DragMove();
        }

        private void MinimizeButton_Click(object sender, RoutedEventArgs e)
        {
            Window? window = Window.GetWindow(this);
            if (window is not null)
            {
                window.WindowState = WindowState.Minimized;
            }
        }

        private void MaximizeButton_Click(object sender, RoutedEventArgs e)
        {
            Window? window = Window.GetWindow(this);
            if (window is null)
            {
                return;
            }

            window.WindowState = window.WindowState == WindowState.Maximized
                ? WindowState.Normal
                : WindowState.Maximized;
        }

        private void CloseButton_Click(object sender, RoutedEventArgs e)
        {
            Window.GetWindow(this)?.Close();
        }
    }
}
